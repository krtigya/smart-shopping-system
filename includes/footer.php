        function generateSignature() {
            const totalEl = document.getElementById('total_amount');
            const txnEl = document.getElementById('transaction_uuid');
            const codeEl = document.getElementById('product_code');
            const secretEl = document.getElementById('secret');
            const sigEl = document.getElementById('signature');
            if (!totalEl || !txnEl || !codeEl || !secretEl || !sigEl) return;

            const now = new Date();
            const pad = (n) => String(n).padStart(2, '0');
            const uuid = now.getFullYear().toString().slice(2) + pad(now.getMonth() + 1) + pad(now.getDate()) + '-' + pad(now.getHours()) + pad(now.getMinutes()) + pad(now.getSeconds());
            txnEl.value = uuid;

            const total = totalEl.value;
            const code = codeEl.value;
            const secret = secretEl.value;
            const message = 'total_amount=' + total + ',transaction_uuid=' + uuid + ',product_code=' + code;
            const hash = CryptoJS.HmacSHA256(message, secret);
            sigEl.value = CryptoJS.enc.Base64.stringify(hash);
